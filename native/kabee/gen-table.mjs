// Reads Kabee's parameter / pedal / board / preset tables out of kabee.wasm and writes them as TypeScript,
// so the ArkaneDAW manifest and editor mirror upstream exactly (Params.hpp + Presets.hpp stay the source of truth).
//
//   node native/kabee/gen-table.mjs <kabee.wasm> <table.gen.ts>
import { readFileSync, writeFileSync } from 'node:fs'

const [wasmPath, outPath] = process.argv.slice(2)
if (!wasmPath || !outPath) {
  console.error('usage: gen-table.mjs <kabee.wasm> <table.gen.ts>')
  process.exit(1)
}

const module = new WebAssembly.Module(readFileSync(wasmPath))
const imports = {}
for (const imp of WebAssembly.Module.imports(module)) {
  if (imp.kind !== 'function') continue
  ;(imports[imp.module] ??= {})[imp.name] = () => 0
}
const { exports: k } = new WebAssembly.Instance(module, imports)
k._initialize?.()

const mem = () => new Uint8Array(k.memory.buffer)
const str = (ptr) => {
  const m = mem()
  let end = ptr
  while (m[end] !== 0) end++
  return new TextDecoder().decode(m.subarray(ptr, end))
}
const round = (v) => Math.round(v * 1e5) / 1e5

const paramCount = k.kabee_param_count()
const params = []
for (let p = 0; p < paramCount; p++) {
  params.push({
    index: p,
    symbol: str(k.kabee_param_symbol(p)),
    name: str(k.kabee_param_name(p)),
    unit: str(k.kabee_param_unit(p)),
    min: round(k.kabee_param_min(p)),
    max: round(k.kabee_param_max(p)),
    def: round(k.kabee_param_def(p)),
    pluginDefault: round(k.kabee_param_default(p)),
    flags: k.kabee_param_flags(p)
  })
}

const pedals = []
for (let i = 0; i < k.kabee_pedal_count(); i++) {
  const knobs = []
  for (let j = 0; j < k.kabee_pedal_knob_count(i); j++)
    knobs.push({ param: k.kabee_pedal_knob_param(i, j), label: str(k.kabee_pedal_knob_label(i, j)), kind: k.kabee_pedal_knob_kind(i, j) === 1 ? 'switch' : 'knob' })
  pedals.push({ id: i, key: str(k.kabee_pedal_key(i)), name: str(k.kabee_pedal_name(i)), onParam: k.kabee_pedal_on_param(i), knobs })
}

const ints = k.kabee_alloc(64 * 4)
const boards = [0, 1].map((mode) => {
  const n = k.kabee_board(mode, ints)
  return Array.from(new Int32Array(k.memory.buffer, ints, n))
})

const values = k.kabee_alloc(paramCount * 4)
const mask = k.kabee_alloc(paramCount)
const readState = () => {
  const v = new Float32Array(k.memory.buffer, values, paramCount)
  const m = new Uint8Array(k.memory.buffer, mask, paramCount)
  const out = {}
  for (let p = 0; p < paramCount; p++) if (m[p]) out[params[p].symbol] = round(v[p])
  return out
}
const presets = []
for (let i = 0; i < k.kabee_preset_count(); i++) {
  k.kabee_preset_state(i, values, mask)
  presets.push({ index: i, name: str(k.kabee_preset_name(i)), mode: k.kabee_preset_mode(i), values: readState() })
}
const newBoards = [0, 1].map((mode) => {
  k.kabee_new_board_state(mode, values, mask)
  return readState()
})
const userPresetParams = [0, 1].map((mode) => params.filter((p) => k.kabee_is_user_preset_param(p.index, mode)).map((p) => p.symbol))

const json = (v) => (Array.isArray(v) ? `[\n${v.map((x) => '  ' + JSON.stringify(x)).join(',\n')}\n]` : JSON.stringify(v))
const src = `// GENERATED by native/kabee/gen-table.mjs from kabee.wasm (upstream Params.hpp / Presets.hpp). Do not edit.
/* eslint-disable */

export interface KabeeParamInfo {
  index: number
  symbol: string
  name: string
  unit: string
  min: number
  max: number
  /** Table default (Params.hpp). */
  def: number
  /** Default of a fresh plugin instance: table defaults with the first factory preset applied. */
  pluginDefault: number
  flags: number
}

export interface KabeeKnobInfo {
  param: number
  label: string
  kind: 'knob' | 'switch'
}

export interface KabeePedalInfo {
  id: number
  key: string
  name: string
  onParam: number
  knobs: KabeeKnobInfo[]
}

export interface KabeeFactoryPreset {
  index: number
  name: string
  /** 0 guitar, 1 bass */
  mode: number
  /** Every parameter the preset owns (mode, chain slots, all pedals of the mode, mic, presence, preset index). */
  values: Record<string, number>
}

export const PF_BOOL = 1
export const PF_INT = 2
export const PF_LOG = 4
export const PF_OUTPUT = 8
export const PF_TRIGGER = 16
export const PF_HIDDEN = 32

export const MAX_SLOTS = ${k.kabee_max_slots()}
export const PRESET_USER = ${k.kabee_preset_count()}
export const PRESET_NEW = ${k.kabee_preset_count() + 1}

export const KABEE_PARAMS: KabeeParamInfo[] = ${json(params)}

export const KABEE_PEDALS: KabeePedalInfo[] = ${json(pedals)}

/** Default board per mode [guitar, bass], in signal order. Also the pedals each mode offers. */
export const KABEE_BOARDS: number[][] = ${json(boards)}

export const KABEE_PRESETS: KabeeFactoryPreset[] = ${json(presets)}

/** NEW: empty board per mode [guitar, bass]. */
export const KABEE_NEW_BOARDS: Record<string, number>[] = ${json(newBoards)}

/** Parameters user presets store, per mode (board + gate on/threshold + output). */
export const KABEE_USER_PRESET_PARAMS: string[][] = ${json(userPresetParams)}
`
writeFileSync(outPath, src)
