// docs/plugins.json: every built-in plugin's id, params (with ranges and defaults) and preset names, so people and
// agents editing .arkane files by hand know what goes in `plugin.pluginId` / `plugin.params`.
// This test fails when the file is stale; `npm run catalog` rewrites it.
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { expect, test } from 'vitest'
import type { PluginManifest } from './sdk/types'

const FILE = resolve(__dirname, '../../../../docs/plugins.json')

function catalog(): unknown {
  const mods = import.meta.glob<{ manifest: PluginManifest }>('./*/manifest.ts', { eager: true })
  const manifests = Object.values(mods)
    .map((m) => m.manifest)
    .sort((a, b) => a.id.localeCompare(b.id))
  return {
    $comment: 'Generated by `npm run catalog` from src/renderer/src/plugins/*/manifest.ts. Do not edit.',
    plugins: manifests.map((m) => ({
      id: m.id,
      name: m.name,
      kind: m.kind,
      category: m.category,
      description: m.description,
      mono: m.mono || undefined,
      hasData: m.defaultData !== undefined || undefined,
      params: m.params.map((p) => ({
        id: p.id,
        name: p.name,
        min: p.min,
        max: p.max,
        default: p.default,
        unit: p.unit,
        step: p.step,
        options: p.options,
        hidden: p.hidden || undefined
      })),
      presets: m.presets?.map((p) => p.name)
    }))
  }
}

test('docs/plugins.json is up to date (npm run catalog)', () => {
  // one line per param keeps the file short and greppable
  const json = JSON.stringify(catalog(), (k, v) => (k === 'params' ? v.map((x: unknown) => `\u0000${JSON.stringify(x)}`) : v), 1)
  const text = `${json.replace(/"\\u0000(.*)"(,?)$/gm, (_, s: string, comma: string) => JSON.parse(`"${s}"`) + comma)}\n`
  if (process.env.UPDATE_CATALOG) writeFileSync(FILE, text)
  let current = ''
  try {
    current = readFileSync(FILE, 'utf8')
  } catch {
    /* missing */
  }
  expect(current === text, 'docs/plugins.json is stale: run `npm run catalog`').toBe(true)
})
