const cache = new Map<string, Uint8Array>()

export function lcdFont(ch: string | undefined): Uint8Array {
  const c = ch ?? ' '
  let g = cache.get(c)
  if (g) return g
  const rows = T[c] ?? T['?']
  g = new Uint8Array(40)
  for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) g[y * 5 + x] = (rows[y] >> (4 - x)) & 1
  cache.set(c, g)
  return g
}
